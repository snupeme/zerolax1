export function useLearningWords() {
  const { language } = useI18n();
  return words[language];
}
export const learningRequest = <T>(
  path: string,
  body?: unknown,
  method: "GET" | "POST" | "PUT" = body === undefined ? "GET" : "POST",
  admin = false,
) =>
  request<T>(`/api/learning/${admin ? "admin" : "user"}${path}`, {
    method,
    body,
    auth: admin ? "admin" : "user",
  });
export async function fetchCertificatePdf(id: string, admin = false) {
  const session = admin ? getStoredAdminSession() : getStoredSession();
  const response = await fetch(
    `${import.meta.env.VITE_API_URL ?? ""}/api/learning/${admin ? "admin" : "user"}/certificates/${id}/pdf`,
    { headers: { authorization: `Bearer ${session?.accessToken}` } },
  );
  if (!response.ok) {
    const body = await response.json();
    throw new Error(body.error?.message ?? "Download failed");
  }
  return response.blob();
}
export async function downloadCertificate(id: string, admin = false) {
  const url = URL.createObjectURL(await fetchCertificatePdf(id, admin));
  const a = document.createElement("a");
  a.href = url;
  a.download = `ZEROLAX-${id}.pdf`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
