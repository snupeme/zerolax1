export function useControlWords() {
  const { language } = useI18n();
  return labels[language];
}
export function toast(message: string, error = false) {
  window.dispatchEvent(
    new CustomEvent("admin-toast", { detail: { message, error } }),
  );
}
export function useUnsaved(dirty: boolean) {
  const w = useControlWords();
  useEffect(() => {
    if (!dirty) return;
    const before = (e: BeforeUnloadEvent) => {
      e.preventDefault();
      e.returnValue = "";
    };
    const click = (e: MouseEvent) => {
      const anchor = (e.target as HTMLElement).closest("a[href]");
      if (anchor && !window.confirm(w.unsaved)) {
        e.preventDefault();
        e.stopPropagation();
      }
    };
    window.addEventListener("beforeunload", before);
    document.addEventListener("click", click, true);
    return () => {
      window.removeEventListener("beforeunload", before);
      document.removeEventListener("click", click, true);
    };
  }, [dirty, w.unsaved]);
}
export async function uploadImage(file: File) {
  if (file.size > 5 * 1024 * 1024) throw new Error("Maximum 5 MB");
  const base64 = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = reject;
    reader.onload = () => resolve(String(reader.result).split(",")[1]);
    reader.readAsDataURL(file);
  });
  return (await control<{ url: string }>("/media", { base64 })).url;
}
export async function downloadReport(kind: string, query: string) {
  const session = getStoredAdminSession();
  const response = await fetch(
    `${import.meta.env.VITE_API_URL ?? ""}/api/admin/control/reports/${kind}?${query}&format=csv`,
    { headers: { authorization: `Bearer ${session?.accessToken}` } },
  );
  if (!response.ok) {
    const b = await response.json();
    throw new Error(b.error?.message ?? "Export failed");
  }
  const url = URL.createObjectURL(await response.blob());
  const a = document.createElement("a");
  a.href = url;
  a.download = `zerolax-${kind}.csv`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
